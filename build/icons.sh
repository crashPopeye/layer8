#!/bin/sh
# Copies the Lucide icons the UI uses into ui/js/icons.js, so the UI keeps no
# build step. To add one, add its name (https://lucide.dev/icons) and rerun.
set -eu
VERSION=1.57.0
ICONS="archive arrow-up check check-check chevron-down chevron-right code-xml external-link file-diff file-text
folder-plus git-commit-horizontal git-fork git-merge git-pull-request git-pull-request-arrow hammer link list-checks
message-square message-square-reply messages-square plus refresh-cw search settings shield square-terminal telescope
trash-2 unlink upload wrench x columns-2 rows-2 panels-top-left layout-dashboard sun moon sun-moon palette puzzle bell"

cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
(cd "$tmp" && npm pack --silent "lucide-static@$VERSION" >/dev/null && tar -xzf lucide-static-*.tgz)
out=ui/js/icons.js
{
  echo "// Generated by build/icons.sh from lucide-static@$VERSION (ISC, see ui/vendor/LICENSE-lucide). Do not edit."
  echo 'import { html } from "/vendor/preact-htm.js";'
  echo
  echo "const PATHS = {"
  for name in $ICONS; do
    svg="$tmp/package/icons/$name.svg"
    test -f "$svg" || { echo "no Lucide icon named $name" >&2; exit 1; }
    # The drawing inside <svg>…</svg>, on one line.
    body=$(tr '\n' ' ' < "$svg" | sed -e 's/.*<svg[^>]*>//' -e 's#</svg>.*##' -e 's/  */ /g' -e 's/> </></g' -e 's/^ //' -e 's/ $//')
    printf '  "%s": `%s`,\n' "$name" "$body"
  done
  echo "};"
  cat <<'JS'

/** A Lucide icon, drawn with the current text colour. */
export const Icon = ({ name, size = 14, stroke = 2 }) =>
  html`<svg class="icon" width=${size} height=${size} viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width=${stroke}
    stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" dangerouslySetInnerHTML=${{ __html: PATHS[name] || "" }} />`;
JS
} > "$out"
cp "$tmp/package/LICENSE" ui/vendor/LICENSE-lucide
echo "wrote $out"
